const ROM: &[u8] = &[];

pub fn initialize(
    frequence_hz: u32,
    rom_file_path: Option<&Path>,
    no_vertical_synchronization: bool,
) -> (
    (Sender<crate::virtual_machine::Speed>, VirtualMachine),
    Window,
) {
    (
        match rom_file_path {
            Some(path) => {
                let (speed_tx, mut virtual_machine) = VirtualMachine::new(
                    frequence_hz,
                    Some(path),
                    None,
                    no_vertical_synchronization,
                );
                virtual_machine.set_font(None);
                (speed_tx, virtual_machine)
            }
            None => {
                let (speed_tx, mut virtual_machine) =
                    VirtualMachine::new(frequence_hz, None, Some(ROM), no_vertical_synchronization);
                virtual_machine.set_font(None);
                (speed_tx, virtual_machine)
            }
        },
        match Window::new("Tuff Virtual Machine", 640, 320, WindowOptions::default()) {
            Ok(win) => win,
            Err(err) => {
                panic!("Unable to create window {}", err);
            }
        },
    )
}
